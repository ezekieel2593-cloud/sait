/**
 * Семь основных чакр: справочник для страницы `chakras.html`.
 *
 * Это описание традиции, а не медицинская информация: мы говорим о том, как
 * чакры принято понимать в практиках самонаблюдения, и о том, где их темы
 * перекликаются со схемой Матрицы судьбы.
 *
 * Важно: числовые значения чакр в школе Матрицы разные авторы считают
 * по-разному (даже формулы для одной чакры отличаются), поэтому мы не
 * выводим «карту здоровья» автоматически — см. limitations в engine.ts.
 * Здесь фиксируется только соответствие «чакра → зона схемы».
 */

export interface ChakraEntry {
  /** 1 — муладхара … 7 — сахасрара. */
  number: number;
  /** Латиницей, для якоря на странице. */
  id: string;
  /** Санскритское название. */
  sanskrit: string;
  /** Как её ещё называют по-русски. */
  russian: string;
  /** Заголовок карточки. */
  title: string;
  /** Где в теле её принято располагать. */
  place: string;
  /** Сфера жизни, за которую она отвечает в традиции. */
  sphere: string;
  /** Стихия. */
  element: string;
  /** Цвет традиции. */
  color: string;
  /** Короткая суть — одна фраза. */
  essence: string;
  /** Как выглядит чакра в балансе. */
  balance: string[];
  /** Как проявляется дисбаланс. */
  imbalance: string[];
  /** Что помогает — бытовые практики, без медицинских обещаний. */
  practice: string[];
  /** Как эта тема читается в схеме Матрицы судьбы. */
  matrix: string;
  /** Формула расчёта значения чакры (версия chakra-22-v1). */
  formula: string;
  /** Ключи точек схемы, о которых идёт речь. */
  matrixPoints: string[];
}

