export function getChakra(idOrNumber: string | number): ChakraEntry | undefined {
  if (typeof idOrNumber === "number") return CHAKRAS.find((chakra) => chakra.number === idOrNumber);
  return CHAKRAS.find((chakra) => chakra.id === idOrNumber);
}
