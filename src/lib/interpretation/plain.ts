/** Бытовое пояснение к разделу: «(что это значит по-простому)». */
export function plainHint(sectionId: string): string | undefined {
  const id = sectionId.replace(/^sec-/, "");
  if (EXACT[id]) return EXACT[id];
  for (const [prefix, hint] of PREFIX) {
    if (id.startsWith(prefix)) return hint;
  }
  return undefined;
}

/** Заголовок с пояснением: «Достоинства планет (где у тебя сила, а где слабость)». */
export function titleWithHint(title: string, sectionId: string): string {
  const hint = plainHint(sectionId);
  return hint ? `${title} (${hint})` : title;
}
